// Emits supabase/seed.sql from the IndiaMART manifest so the admin CMS is backed by
// the same real data the static site ships with.
// Run: node scripts/generate-seed-sql.mjs
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const manifest = JSON.parse(await readFile(path.join(import.meta.dirname, 'indiamart-manifest.json'), 'utf8'));

const esc = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v == null ? 'NULL' : v);

const catBySlug = Object.fromEntries(manifest.categories.map((c) => [c.id, c]));

const lines = [
  '-- AUTO-GENERATED by scripts/generate-seed-sql.mjs — do not edit by hand.',
  '-- Real BCare catalogue migrated from https://www.indiamart.com/bcare/',
  '-- Safe to re-run: upserts on slug, and child rows are replaced per product.',
  '',
  'BEGIN;',
  '',
  '-- Storage buckets used by the admin media library and product uploads.',
  "INSERT INTO storage.buckets (id, name, public) VALUES",
  "  ('products','products',true), ('gallery','gallery',true), ('videos','videos',true),",
  "  ('brand-assets','brand-assets',true), ('documents','documents',true), ('media','media',true)",
  'ON CONFLICT (id) DO NOTHING;',
  '',
  '-- ---------- Categories ----------',
];

for (const c of manifest.categories) {
  const hero = manifest.products.find((p) => p.category === c.id);
  lines.push(
    `INSERT INTO product_categories (name, slug, description, image_url, is_active) VALUES (${esc(c.name)}, ${esc(
      c.id
    )}, ${esc(c.description)}, ${esc(`/products/${hero.slug}/main.webp`)}, true)`,
    `ON CONFLICT (slug) DO UPDATE SET name=EXCLUDED.name, description=EXCLUDED.description, image_url=EXCLUDED.image_url, is_active=true;`
  );
}

lines.push('', '-- ---------- Products ----------');

for (const p of manifest.products) {
  const dir = path.join(ROOT, 'public', 'products', p.slug);
  const files = existsSync(dir) ? (await readdir(dir)).filter((f) => f.endsWith('.webp')) : [];
  const images = [
    ...(files.includes('main.webp') ? ['main.webp'] : []),
    ...files.filter((f) => f !== 'main.webp').sort((a, b) => a.localeCompare(b, 'en', { numeric: true })),
  ].map((f) => `/products/${p.slug}/${f}`);

  const seoTitle = `${p.name} | BCare Bakery & Kitchen Equipments, Thrissur Kerala`;
  const priceText = p.price ? `Price Rs ${p.price.toLocaleString('en-IN')} per ${p.priceUnit.toLowerCase()}.` : 'Price on request.';
  const seoDesc = `${p.shortDescription} ${priceText} Supplied by BCare Bakery & Kitchen Equipments, Nadathara, Thrissur, Kerala.`.slice(0, 300);

  lines.push(
    '',
    `-- ${p.name}`,
    `INSERT INTO products (category_id, name, slug, sku, badge, price, price_on_request, availability, short_description, description, featured_image, status, seo_title, seo_description)`,
    `SELECT c.id, ${esc(p.name)}, ${esc(p.slug)}, ${esc(p.sku)}, ${esc(p.brand)}, ${num(p.price)}, ${
      p.price == null ? 'true' : 'false'
    }, 'In Stock', ${esc(p.shortDescription)}, ${esc(p.description)}, ${esc(images[0])}, 'published', ${esc(
      seoTitle
    )}, ${esc(seoDesc)}`,
    `FROM product_categories c WHERE c.slug = ${esc(p.category)}`,
    `ON CONFLICT (slug) DO UPDATE SET category_id=EXCLUDED.category_id, name=EXCLUDED.name, sku=EXCLUDED.sku, badge=EXCLUDED.badge,`,
    `  price=EXCLUDED.price, price_on_request=EXCLUDED.price_on_request, short_description=EXCLUDED.short_description,`,
    `  description=EXCLUDED.description, featured_image=EXCLUDED.featured_image, status='published',`,
    `  seo_title=EXCLUDED.seo_title, seo_description=EXCLUDED.seo_description, updated_at=NOW();`,
    `DELETE FROM product_images WHERE product_id = (SELECT id FROM products WHERE slug = ${esc(p.slug)});`
  );

  images.forEach((url, i) => {
    const alt = i === 0 ? `${p.name} — BCare Bakery & Kitchen Equipments` : `${p.name} view ${i + 1}`;
    lines.push(
      `INSERT INTO product_images (product_id, image_url, alt_text, display_order) SELECT id, ${esc(url)}, ${esc(
        alt
      )}, ${i} FROM products WHERE slug = ${esc(p.slug)};`
    );
  });

  lines.push(`DELETE FROM product_specifications WHERE product_id = (SELECT id FROM products WHERE slug = ${esc(p.slug)});`);
  Object.entries(p.specifications).forEach(([k, v], i) => {
    lines.push(
      `INSERT INTO product_specifications (product_id, specification_name, specification_value, display_order) SELECT id, ${esc(
        k
      )}, ${esc(v)}, ${i} FROM products WHERE slug = ${esc(p.slug)};`
    );
  });
}

// IndiaMART publishes one shared BCare catalogue rather than per-product brochures.
const CATALOGUE_PDF = '/documents/bcare-product-catalogue.pdf';
if (existsSync(path.join(ROOT, 'public', CATALOGUE_PDF.slice(1)))) {
  lines.push('', '-- ---------- Product documents (shared BCare catalogue) ----------', 'DELETE FROM product_documents;');
  for (const p of manifest.products) {
    lines.push(
      `INSERT INTO product_documents (product_id, file_name, file_url, document_type) SELECT id, ${esc(
        'BCare Product Catalogue.pdf'
      )}, ${esc(CATALOGUE_PDF)}, 'brochure' FROM products WHERE slug = ${esc(p.slug)};`
    );
  }
}

lines.push('', '-- ---------- Gallery (real equipment photography) ----------', 'DELETE FROM gallery;');
for (const p of manifest.products) {
  const dir = path.join(ROOT, 'public', 'products', p.slug);
  const files = existsSync(dir) ? (await readdir(dir)).filter((f) => f.endsWith('.webp')) : [];
  for (const f of files) {
    lines.push(
      `INSERT INTO gallery (title, album, image_url, caption) VALUES (${esc(p.name)}, ${esc(
        catBySlug[p.category].name
      )}, ${esc(`/products/${p.slug}/${f}`)}, ${esc(p.shortDescription)});`
    );
  }
}

lines.push('', '-- ---------- Videos ----------', 'DELETE FROM videos;');
for (const v of manifest.videos) {
  const prod = manifest.products.find((p) => p.slug === v.productSlug);
  lines.push(
    `INSERT INTO videos (title, youtube_url, thumbnail_url, category, description) VALUES (${esc(
      v.title
    )}, ${esc(`https://www.youtube.com/watch?v=${v.youtubeId}`)}, ${esc(
      `https://img.youtube.com/vi/${v.youtubeId}/maxresdefault.jpg`
    )}, 'Product Demo', ${esc(prod?.shortDescription ?? '')});`
  );
}

lines.push(
  '',
  '-- ---------- Verified IndiaMART buyer reviews ----------',
  'DELETE FROM google_reviews;',
  `INSERT INTO google_reviews (customer_name, rating, review_text, location, source, is_approved) VALUES`,
  `  ('Sreeni', 5, 'good machiners and best service', 'Thrissur, Kerala', 'indiamart', true),`,
  `  ('Swalah', 5, 'Great Service Team & Quality', 'Thrissur, Kerala', 'indiamart', true);`,
  '',
  'COMMIT;'
);

await writeFile(path.join(ROOT, 'supabase', 'seed.sql'), lines.join('\n') + '\n', 'utf8');
console.log(`Wrote supabase/seed.sql (${lines.length} statements/lines)`);
